use agent_channel::model::{CONNECT_TIMEOUT_SECONDS, PREFERRED_RETRY_SECONDS, SERVER_KEEPALIVE_INTERVAL_SECONDS, UNARY_TIMEOUT_SECONDS};
use relay::model::{
    AGENT_CONNECT_TIMEOUT_SECONDS, AGENT_KEEPALIVE_SECONDS, AGENT_PREFERRED_RETRY_SECONDS, AGENT_UNARY_TIMEOUT_SECONDS, KEEPALIVE_FACTOR,
    LIFETIME_MARGIN_SECONDS, MIN_IDLE_SECONDS, MIN_LIFETIME_SECONDS,
};


#[test]
fn the_mirrored_agent_constants_match_agent_channel() -> Result<(), String> {
    assert_eq!(AGENT_CONNECT_TIMEOUT_SECONDS, CONNECT_TIMEOUT_SECONDS);
    assert_eq!(AGENT_KEEPALIVE_SECONDS, SERVER_KEEPALIVE_INTERVAL_SECONDS);
    assert_eq!(AGENT_UNARY_TIMEOUT_SECONDS, UNARY_TIMEOUT_SECONDS);
    assert_eq!(AGENT_PREFERRED_RETRY_SECONDS, PREFERRED_RETRY_SECONDS);
    Ok(())
}


#[test]
fn the_minimums_follow_the_agent() -> Result<(), String> {
    assert_eq!(MIN_IDLE_SECONDS, SERVER_KEEPALIVE_INTERVAL_SECONDS * KEEPALIVE_FACTOR);
    assert_eq!(
        MIN_LIFETIME_SECONDS,
        PREFERRED_RETRY_SECONDS + UNARY_TIMEOUT_SECONDS + LIFETIME_MARGIN_SECONDS
    );
    Ok(())
}
