//! The fixed winget update listing the agent runs, as text and as its `-EncodedCommand` form.


/// The PowerShell script: one compact JSON envelope `{Updates[]}` on stdout, every character above U+007E written as a `\uXXXX` escape.
pub const WINGET_SCRIPT: &str = r#"$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
Remove-TypeData System.Array -ErrorAction SilentlyContinue
[Console]::OutputEncoding = New-Object System.Text.UTF8Encoding $false
Import-Module Microsoft.WinGet.Client
$updates = foreach ($package in @(Microsoft.WinGet.Client\Get-WinGetPackage | Where-Object { $_.IsUpdateAvailable })) {
    [pscustomobject]@{
        Id = [string]$package.Id
        InstalledVersion = [string]$package.InstalledVersion
        AvailableVersion = [string]@($package.AvailableVersions)[0]
        Source = [string]$package.Source
    }
}
$envelope = [pscustomobject]@{ Updates = [object[]]@($updates) }
$json = ConvertTo-Json -InputObject $envelope -Compress -Depth 3
[Console]::Out.Write([regex]::Replace($json, '[\u007F-\uFFFF]', { param($m) '\u{0:x4}' -f [int][char]$m.Value }))
"#;


