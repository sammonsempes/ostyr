//! The fixed winget update listing the agent runs, as text and as its `-EncodedCommand` form.


/// The PowerShell script: one compact JSON envelope `{Updates[]}` on stdout, every character above U+007E written as a `\uXXXX` escape.
pub const WINGET_SCRIPT: &str = r#"$env:Path = 'C:\Windows\System32'
$env:PSModulePath = 'C:\Windows\System32\WindowsPowerShell\v1.0\Modules;C:\Program Files\WindowsPowerShell\Modules'
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
Microsoft.PowerShell.Utility\Remove-TypeData System.Array -ErrorAction SilentlyContinue
[Console]::OutputEncoding = Microsoft.PowerShell.Utility\New-Object System.Text.UTF8Encoding $false
Microsoft.PowerShell.Core\Import-Module Microsoft.WinGet.Client
$updates = foreach ($package in @(Microsoft.WinGet.Client\Get-WinGetPackage | Microsoft.PowerShell.Core\Where-Object { $_.IsUpdateAvailable })) {
    [pscustomobject]@{
        Id = [string]$package.Id
        InstalledVersion = [string]$package.InstalledVersion
        AvailableVersion = [string]@($package.AvailableVersions)[0]
        Source = [string]$package.Source
    }
}
$envelope = [pscustomobject]@{ Updates = [object[]]@($updates) }
$json = Microsoft.PowerShell.Utility\ConvertTo-Json -InputObject $envelope -Compress -Depth 3
[Console]::Out.Write([regex]::Replace($json, '[\u007F-\uFFFF]', { param($m) '\u{0:x4}' -f [int][char]$m.Value }))
"#;


