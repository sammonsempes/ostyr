//! The fixed Windows Update Agent search the agent runs, as text and as its `-EncodedCommand` form.


/// The PowerShell search script: one compact JSON envelope on stdout, every character above U+007E written as a `\uXXXX` escape.
pub const WUA_SEARCH_SCRIPT: &str = r#"$env:Path = 'C:\Windows\System32'
$env:PSModulePath = 'C:\Windows\System32\WindowsPowerShell\v1.0\Modules'
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
Microsoft.PowerShell.Utility\Remove-TypeData System.Array -ErrorAction SilentlyContinue
[Console]::OutputEncoding = Microsoft.PowerShell.Utility\New-Object System.Text.UTF8Encoding $false
$session = Microsoft.PowerShell.Utility\New-Object -ComObject Microsoft.Update.Session
$result = $session.CreateUpdateSearcher().Search("IsInstalled=0 and Type='Software'")
$updates = foreach ($update in $result.Updates) {
    [pscustomobject]@{
        UpdateID = $update.Identity.UpdateID
        RevisionNumber = [int]$update.Identity.RevisionNumber
        KBArticleIDs = [string[]]@($update.KBArticleIDs)
        Title = [string]$update.Title
        MsrcSeverity = [string]$update.MsrcSeverity
        CategoryIDs = [string[]]@($update.Categories | Microsoft.PowerShell.Core\ForEach-Object { $_.CategoryID })
        IsHidden = [bool]$update.IsHidden
        IsMandatory = [bool]$update.IsMandatory
        RebootBehavior = [int]$update.InstallationBehavior.RebootBehavior
    }
}
$envelope = [pscustomobject]@{ ResultCode = [int]$result.ResultCode; Updates = [object[]]@($updates) }
$json = Microsoft.PowerShell.Utility\ConvertTo-Json -InputObject $envelope -Compress -Depth 4
[Console]::Out.Write([regex]::Replace($json, '[\u007F-\uFFFF]', { param($m) '\u{0:x4}' -f [int][char]$m.Value }))
"#;


